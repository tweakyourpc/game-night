import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { createRequire } from 'node:module';
import { execFileSync } from 'node:child_process';
import { auditTree, verifyInventory, hash } from './release-audit.mjs';
const require=createRequire(import.meta.url), a=require('./assemble.js');
const root=a.ROOT, version=JSON.parse(fs.readFileSync(path.join(root,'package.json'))).version;
verifyInventory(); auditTree(root);
const out=path.join(root,'dist/apps-script');
fs.mkdirSync(out,{recursive:true});
const code='// Game Night '+version+' | MIT | Copyright (c) 2026 Game Night contributors\n'+a.serverBundle();
new vm.Script(code);
if (/\brequire\s*\(|^\s*(?:import|export)\s/m.test(code)) throw Error('Unresolved server module');
const html=a.page(null);
for(const m of html.replace('<?!= boot ?>','{}').matchAll(/<script[^>]*>([\s\S]*?)<\/script>/gi)) new vm.Script(m[1]);
if (/\/\*@inline|\/\*@boot|(?:src|href)=["'](?:\.\.?\/|\/src\/)/.test(html)) throw Error('Unresolved page asset');
const files={'Code.gs':code,'Index.html':html,'appsscript.json':fs.readFileSync(path.join(root,'src/appsscript/appsscript.json'))};
for(const id of ['maple','walnut','felt','slate']) files['asset_wordwright_board_'+id+'.html']='data:image/jpeg;base64,'+fs.readFileSync(path.join(root,'assets/wordwright/board-'+id+'.jpg')).toString('base64');
for(const old of fs.readdirSync(out)) if (!(old in files) && old !== 'MANIFEST.txt') throw Error('Unexpected stale build file: '+old);
for(const [name,data] of Object.entries(files)) fs.writeFileSync(path.join(out,name),data);
fs.writeFileSync(path.join(out,'MANIFEST.txt'),'Game Night '+version+'\nSee ../docs/install.md. Paste these files into a NEW bound Apps Script project.\n\n'+Object.keys(files).map(n=>n+'  '+hash(Buffer.from(files[n]))).join('\n')+'\n\nCode.gs: Script file Code. Index and asset_*: HTML files, omit extension in editor.\nappsscript.json: enable manifest in Project Settings. Do not upload this manifest text file.\n');
const stage=fs.mkdtempSync('/tmp/game-night-release-'), kit=path.join(stage,'game-night-v'+version);
fs.mkdirSync(kit);
for(const name of ['README.md','LICENSE','NOTICE.md','VERSION','CHANGELOG.md','.clasp.json.example','docs','tools/effectcraft','assets','assets_src']) fs.cpSync(path.join(root,name),path.join(kit,name),{recursive:true});
// The historical plan is source design history, not installation instructions.
fs.rmSync(path.join(kit,'docs/PLAN.md'),{force:true});
fs.cpSync(out,path.join(kit,'apps-script'),{recursive:true});
auditTree(kit);
const zip=path.join(root,'dist/game-night-v'+version+'.zip');
fs.rmSync(zip,{force:true});
execFileSync('zip',['-q','-r',zip,path.basename(kit)],{cwd:stage});
const unpack=fs.mkdtempSync('/tmp/game-night-zip-audit-');
execFileSync('unzip',['-q',zip,'-d',unpack]);
auditTree(unpack);
fs.rmSync(stage,{recursive:true,force:true}); fs.rmSync(unpack,{recursive:true,force:true});
console.log('Built '+out+'\nAudited '+zip);
